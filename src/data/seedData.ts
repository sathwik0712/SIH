// Helper to generate coordinates around a base center
function generatePolygon(centerLat: number, centerLng: number, offsetLat: number, offsetLng: number, size = 0.004) {
  const cLat = centerLat + offsetLat;
  const cLng = centerLng + offsetLng;
  return {
    center: { lat: cLat, lng: cLng },
    polygon: [
      { lat: +(cLat - size * 0.4).toFixed(6), lng: +(cLng - size * 0.5).toFixed(6) },
      { lat: +(cLat + size * 0.4).toFixed(6), lng: +(cLng - size * 0.4).toFixed(6) },
      { lat: +(cLat + size * 0.5).toFixed(6), lng: +(cLng + size * 0.5).toFixed(6) },
      { lat: +(cLat - size * 0.3).toFixed(6), lng: +(cLng + size * 0.4).toFixed(6) },
    ]
  };
}

